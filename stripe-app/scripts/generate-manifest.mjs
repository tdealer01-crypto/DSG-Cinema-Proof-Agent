import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '..');
const backend = (process.env.CINEMA_API_BASE || '').replace(/\/$/, '');

if (!backend.startsWith('https://')) {
  throw new Error('CINEMA_API_BASE must be an HTTPS URL');
}

const templatePath = path.join(root, 'stripe-app.template.json');
const manifestPath = path.join(root, 'stripe-app.json');
const runtimePath = path.join(root, 'src', 'runtime.ts');

const template = await readFile(templatePath, 'utf8');
if (!template.includes('__CINEMA_API_BASE__')) {
  throw new Error('Manifest template does not contain the backend placeholder');
}

const manifest = template.replaceAll('__CINEMA_API_BASE__', backend);
const parsed = JSON.parse(manifest);

if (parsed.id !== 'pics.dsg.governance' || parsed.version !== '2.7.0') {
  throw new Error('Unexpected Stripe app identity or version');
}

if (manifest.includes('tdealer01-crypto-dsg-control-plane') || manifest.includes('dsg-stripe-app.vercel.app')) {
  throw new Error('Legacy Control Plane URL detected in generated manifest');
}

// Stripe fetches every redirect URL during review, so one pointing at a host
// this build does not serve fails the submission rather than the build.
const redirectUrls = parsed.oauth?.redirect_urls ?? [];
if (redirectUrls.length === 0) {
  throw new Error('Manifest declares no OAuth redirect URL');
}
for (const url of redirectUrls) {
  if (!url.startsWith(`${backend}/`)) {
    throw new Error(`OAuth redirect URL is not served by this backend: ${url}`);
  }
}

await writeFile(manifestPath, `${JSON.stringify(parsed, null, 2)}\n`);
await writeFile(
  runtimePath,
  `// Generated by scripts/generate-manifest.mjs.\nexport const CINEMA_API_BASE = ${JSON.stringify(backend)};\n`,
);

console.log(`Generated Stripe App v${parsed.version} for ${backend}`);
